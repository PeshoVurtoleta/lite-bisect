// test/gen.test.mjs -- assertion 4 (SPEC-p1 U3 T4). scripts/gen.mjs --check / write mode.
// Every row spawns gen with process.execPath and asserts the exit code EXACTLY. gen exits 1
// both for "differs" and for an uncaught throw, so every exit-1 row also asserts the output
// carries the "differs" line with "byte offset" and the EXPECTED offset (a crash is not a
// kill). Scratch files live in a mkdtemp dir under os.tmpdir(), removed in finally; every
// row except the live check passes --file <scratch copy>, and the live Bisect.js bytes are
// asserted unchanged at the end.

import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, copyFileSync, mkdtempSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TYPE_NAMES } from './oracle.mjs';

const GEN = fileURLToPath(new URL('../scripts/gen.mjs', import.meta.url));
const TEMPLATE = fileURLToPath(new URL('../scripts/bisect.template.js', import.meta.url));
const BISECT = fileURLToPath(new URL('../Bisect.js', import.meta.url));
const BEGIN = '// BEGIN GENERATED by scripts/gen.mjs from scripts/bisect.template.js -- edit the template, then npm run gen';
const END = '// END GENERATED by scripts/gen.mjs';
const TYPES = TYPE_NAMES;

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
const LIVE_SHA = sha(readFileSync(BISECT));
after(() => {
    assert.equal(sha(readFileSync(BISECT)), LIVE_SHA, 'gen.test modified the live Bisect.js');
});

function gen(args) {
    const r = spawnSync(process.execPath, [GEN, ...args], { encoding: 'utf8', timeout: 30000 });
    assert.equal(r.error, undefined, 'spawn error: ' + r.error);
    assert.equal(r.signal, null, 'gen killed by ' + r.signal);
    return { status: r.status, out: (r.stdout || '') + (r.stderr || '') };
}

function withScratch(fn) {
    const dir = mkdtempSync(join(tmpdir(), 'lite-bisect-gen-'));
    try { return fn(dir); } finally { rmSync(dir, { recursive: true, force: true }); }
}

// One output line with "differs", "byte offset" and the expected offset as a whole number.
function assertDiffers(out, offset) {
    const re = new RegExp('(^|[^0-9])' + offset + '([^0-9]|$)');
    const ok = out.split('\n').some((l) => l.includes('differs') && l.includes('byte offset') && re.test(l));
    assert.ok(ok, 'no "differs ... byte offset ' + offset + '" line; gen output:\n' + out);
}

// [start, end) of the generated region: after the BEGIN marker line, before the END marker line.
function region(text) {
    const b = text.indexOf(BEGIN + '\n');
    const e = text.indexOf('\n' + END + '\n');
    assert.ok(b >= 0 && e > b, 'markers not found in Bisect.js');
    return { start: b + BEGIN.length + 1, end: e + 1 };
}

test('gen --check exits 0 on the live tree', () => {
    const r = gen(['--check']);
    assert.equal(r.status, 0, r.out);
});

test('gen --check exits 1 with one in-region byte flipped (scratch copy), naming its offset', () => {
    withScratch((dir) => {
        const live = readFileSync(BISECT);
        const { start, end } = region(live.toString('latin1'));
        const off = start + ((end - start) >> 1);
        const buf = Buffer.from(live);
        buf[off] = buf[off] === 0x61 ? 0x62 : 0x61;   // 'a' / 'b': stays ASCII
        let diff = 0;
        for (let i = 0; i < buf.length; i++) if (buf[i] !== live[i]) diff++;
        assert.equal(diff, 1, 'scratch copy must differ in exactly one byte');
        const p = join(dir, 'Bisect.js');
        writeFileSync(p, buf);
        const r = gen(['--check', '--file', p]);
        assert.equal(r.status, 1, r.out);
        assertDiffers(r.out, off);
    });
});

test('gen --check exits 1 with a template copy with one body byte changed, naming the offset', () => {
    withScratch((dir) => {
        const tpl = readFileSync(TEMPLATE, 'utf8');
        const live = readFileSync(BISECT, 'utf8');
        const lines = tpl.split('\n');
        // The first digit in a body line (a line after an `export function <kernel>$T(` line,
        // before the closing `}`) that holds no `$`, so the generated line is the template line.
        let li = -1, col = -1, kernel = null, rel = -1;
        for (let i = 0, cur = null, k = 0; i < lines.length && li < 0; i++) {
            const m = /^export function ([A-Za-z0-9_]+)\$T\(/.exec(lines[i]);
            if (m) { cur = m[1]; k = 0; continue; }
            if (cur === null) continue;
            if (lines[i] === '}') { cur = null; continue; }
            k++;
            if (lines[i].includes('$')) continue;
            const d = lines[i].search(/[0-9]/);
            if (d >= 0) { li = i; col = d; kernel = cur; rel = k; }
        }
        assert.ok(li >= 0, 'NOT-APPLIED: no digit found in a template body line without $');
        const line = lines[li];
        const ch = line[col];
        const mutLine = line.slice(0, col) + (ch === '1' ? '2' : '1') + line.slice(col + 1);
        lines[li] = mutLine;
        const tplMut = lines.join('\n');
        assert.equal(tplMut.length, tpl.length);
        // Expected first differing offset in Bisect.js: the earliest generated copy of that line.
        let expected = Infinity;
        for (const T of TYPES) {
            const head = 'export function ' + kernel + T + '(';
            const at = live.indexOf(head);
            assert.ok(at >= 0, 'NOT-APPLIED: ' + head + ' not in Bisect.js');
            let ls = live.indexOf('\n', at) + 1;
            for (let j = 1; j < rel; j++) ls = live.indexOf('\n', ls) + 1;
            const le = live.indexOf('\n', ls);
            assert.equal(live.slice(ls, le), line, 'NOT-APPLIED: generated line of ' + kernel + T + ' differs from the template line');
            expected = Math.min(expected, Buffer.byteLength(live.slice(0, ls), 'utf8') + col);
        }
        const tp = join(dir, 'bisect.template.js');
        writeFileSync(tp, tplMut);
        const fp = join(dir, 'Bisect.js');
        copyFileSync(BISECT, fp);
        const r = gen(['--check', '--file', fp, '--template', tp]);
        assert.equal(r.status, 1, r.out);
        assertDiffers(r.out, expected);
    });
});

test('gen --check exits 2 with the end marker deleted', () => {
    withScratch((dir) => {
        const live = readFileSync(BISECT, 'utf8');
        const at = live.indexOf('\n' + END + '\n');
        assert.ok(at >= 0 && live.indexOf('\n' + END + '\n', at + 1) < 0, 'NOT-APPLIED: end marker not found once');
        const cut = live.slice(0, at + 1) + live.slice(at + 1 + END.length + 1);
        assert.equal(cut.includes(END), false);
        const p = join(dir, 'Bisect.js');
        writeFileSync(p, cut);
        const r = gen(['--check', '--file', p]);
        assert.equal(r.status, 2, r.out);
    });
});

test('gen --check exits 2 with no Bisect.js (--file names a missing path)', () => {
    withScratch((dir) => {
        const r = gen(['--check', '--file', join(dir, 'missing', 'Bisect.js')]);
        assert.equal(r.status, 2, r.out);
    });
});

test('gen write mode: a flipped scratch copy is restored, then a second run is a 0-byte diff', () => {
    withScratch((dir) => {
        const live = readFileSync(BISECT);
        const { start, end } = region(live.toString('latin1'));
        const off = start + ((end - start) >> 1);
        const buf = Buffer.from(live);
        buf[off] = buf[off] === 0x61 ? 0x62 : 0x61;
        const p = join(dir, 'Bisect.js');
        writeFileSync(p, buf);
        const r1 = gen(['--file', p]);
        assert.equal(r1.status, 0, r1.out);
        const after1 = readFileSync(p);
        assert.equal(Buffer.compare(after1, live), 0, 'write run 1 did not regenerate the region');
        const r2 = gen(['--file', p]);
        assert.equal(r2.status, 0, r2.out);
        const after2 = readFileSync(p);
        assert.equal(Buffer.compare(after2, after1), 0, 'write run 2 changed bytes');
        const r3 = gen(['--check', '--file', p]);
        assert.equal(r3.status, 0, r3.out);
    });
});
