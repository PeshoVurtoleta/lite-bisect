// scripts/gen.mjs -- dev only (not in files[]). Writes the per-type copies of
// scripts/bisect.template.js into Bisect.js, between the two marker lines.
//   node scripts/gen.mjs            write mode (idempotent: rewrites only the region, only if it changed)
//   node scripts/gen.mjs --check    exit 0 equal, 1 any byte differs (prints the first offset), 2 refused
//   --file <path>  target (default ../Bisect.js from this script); --template <path> (default ./bisect.template.js)
// Exit 2: missing target or template, bad markers, or a refused template (non-ASCII byte, CR, other
// control byte, a $T count != EXPECTED_T, a leftover `$` after substitution, no trailing LF).
// Region = the bytes after the begin marker line's LF up to the start of the end marker line:
// for each type in TYPES order, the template from its first `export function` line to EOF with
// every $T replaced by the suffix; the per-type blocks are joined by one blank line.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const TYPES = ['F64', 'F32', 'U32', 'U16', 'I32'];
// Per type: 7 declarations + 2 calls in lowerBoundHint + 1 in segment + 1 in nearest.
const EXPECTED_T = 11;
const BEGIN = '// BEGIN GENERATED by scripts/gen.mjs from scripts/bisect.template.js -- edit the template, then npm run gen';
const END = '// END GENERATED by scripts/gen.mjs';

const refuse = (m) => { console.error('gen: ' + m); process.exit(2); };

let file = fileURLToPath(new URL('../Bisect.js', import.meta.url));
let template = fileURLToPath(new URL('./bisect.template.js', import.meta.url));
let check = false;
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') check = true;
    else if (a === '--file' || a === '--template') {
        const v = argv[++i];
        if (v === undefined || v.startsWith('--')) refuse(a + ' needs a path');
        if (a === '--file') file = resolve(v); else template = resolve(v);
    } else refuse('unknown argument ' + JSON.stringify(a) + ' (known: --check, --file <path>, --template <path>)');
}

if (!existsSync(template)) refuse('template not found: ' + template);
if (!existsSync(file)) refuse('target not found: ' + file + ' (write its header with the two marker lines first)');

// ---- template: refuse before substituting ----
const tbuf = readFileSync(template);
for (let i = 0; i < tbuf.length; i++) {
    const c = tbuf[i];
    if (c === 13) refuse('template has a CR at byte ' + i + ' (LF only)');
    if (c > 0x7e) refuse('template has a non-ASCII byte 0x' + c.toString(16) + ' at byte ' + i);
    if (c < 0x20 && c !== 10 && c !== 9) refuse('template has a control byte 0x' + c.toString(16) + ' at byte ' + i);
}
const ttext = tbuf.toString('latin1');
if (!ttext.endsWith('}\n') || ttext.endsWith('\n\n')) refuse('template must end with `}` and exactly one LF');
const tcount = ttext.split('$T').length - 1;
if (tcount !== EXPECTED_T) refuse('template has ' + tcount + ' $T, expected ' + EXPECTED_T);
const start = ttext.startsWith('export function ') ? 0 : ttext.indexOf('\nexport function ') + 1;
if (start === 0 && !ttext.startsWith('export function ')) refuse('template has no `export function` line');
const fnText = ttext.slice(start);
if (ttext.slice(0, start).includes('$')) refuse('template header contains a `$`');
const blocks = [];
for (const t of TYPES) {
    const b = fnText.split('$T').join(t);
    const d = b.indexOf('$');
    if (d >= 0) refuse('leftover `$` after substitution (' + t + ') at function-text offset ' + d);
    blocks.push(b);
}
const region = blocks.join('\n');

// ---- target: exactly one begin marker line before exactly one end marker line ----
const fbuf = readFileSync(file);
const ftext = fbuf.toString('latin1');
const nb = ftext.split(BEGIN).length - 1;
const ne = ftext.split(END).length - 1;
if (nb !== 1 || ne !== 1) refuse('target needs exactly one begin and one end marker (found ' + nb + ' / ' + ne + '): ' + file);
const bi = ftext.indexOf(BEGIN);
const ei = ftext.indexOf(END);
const rs = bi + BEGIN.length + 1;
if (!(bi < ei)) refuse('begin marker is not before the end marker: ' + file);
if ((bi > 0 && ftext[bi - 1] !== '\n') || ftext[rs - 1] !== '\n') refuse('begin marker must be a whole line: ' + file);
if (ftext[ei - 1] !== '\n' || ei < rs) refuse('end marker must start its own line after the begin marker line: ' + file);

const want = Buffer.from(ftext.slice(0, rs) + region + ftext.slice(ei), 'latin1');

if (check) {
    if (want.equals(fbuf)) { console.log('gen --check: ok ' + file); process.exit(0); }
    const m = Math.min(want.length, fbuf.length);
    let off = 0;
    while (off < m && want[off] === fbuf[off]) off++;
    console.error('gen --check: ' + file + ' differs from the template at byte offset ' + off + ' (generated ' + want.length + ' B, file ' + fbuf.length + ' B); run npm run gen');
    process.exit(1);
}
if (want.equals(fbuf)) { console.log('gen: up to date ' + file); process.exit(0); }
writeFileSync(file, want);
console.log('gen: wrote ' + file + ' (' + TYPES.length + ' types, region ' + region.length + ' B)');
