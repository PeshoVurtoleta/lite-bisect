/**
 * @zakkster/lite-bisect -- zero-GC binary search kernels for sorted typed arrays.
 * One monomorphic copy of every kernel per array type, suffix F64 / F32 / U32 / U16 / I32
 * (Float64Array, Float32Array, Uint32Array, Uint16Array, Int32Array).
 *
 * Contract (every kernel):
 *   a         a sorted, non-decreasing typed array of the suffix's type, no NaN inside.
 *   [lo, hi)  the half-open range searched: integers, 0 <= lo <= hi <= a.length, hi - lo <= 2^30 - 1.
 *   lower     lowerBound*: the first i in [lo, hi) with a[i] >= x, else hi.
 *   upper     upperBound*: the first i in [lo, hi) with a[i] >  x, else hi.
 *   hint      lowerBoundHint*(a, lo, hi, x, h): lower, galloping out from h. h is an integer index or
 *             NaN (NaN -> lo; outside [lo, hi] clamped); a non-integer h is a caller error that may
 *             return a wrong index or never return.
 *   segment   upper - 1: the last i with a[i] <= x; lo - 1 when x < a[lo], on NaN, on an empty range.
 *   nearest   the index closest to x: a tie between the last value below x and the first above goes
 *             to the LOWER one; an exact match wins (the first i with a[i] === x); within a run of
 *             equal values, the index next to x; an empty range -> lo, NaN -> lo.
 *   A NaN query compares false everywhere: every lower / upper / hint kernel returns lo.
 *
 * Allocation: zero allocation where the kernel inlines into its caller, or the query is a Smi; a non-Smi number query passed across a call V8 does not inline boxes one 16 B HeapNumber.
 *
 * The hot kernels trust the caller: no range check, no throw. A range outside the
 * contract may return a wrong index or never return. The cold checks assertRange(a, lo, hi) and
 * assertSorted(a, lo, hi) throw RangeError; call them off the hot path. No kernel calls them.
 *
 * MIT (c) Zahary Shinikchiev <shinikchiev@yahoo.com>
 */

