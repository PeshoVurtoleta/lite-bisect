export function lowerBoundBranchlessF64(a, lo, hi, x) {
    let n = hi - lo;
    if (n === 0) return lo;              // a[b] below would read outside the range
    let b = lo;
    while (n > 1) {
        const h = n >>> 1;
        b += (0 - ((a[b + h] < x) | 0)) & h;
        n -= h;
    }
    return b + ((a[b] < x) | 0);
}

